    private static SampleDocument Invoice(string fileName, DateTime date, string number, string dateText, string item, string total) =>
        new(fileName, date, $"СЧЕТ НА ОПЛАТУ № {number} от {dateText}",
        [
            Seller,
            Buyer,
            $"Наименование: {item}",
            $"Итого к оплате: {total} руб., в т. ч. НДС 20%",
            "Счет действителен к оплате в течение 5 банковских дней.",
        ]);

    private static SampleDocument Act(string fileName, DateTime date, string number, string dateText, string contract) =>
        new(fileName, date, $"АКТ ВЫПОЛНЕННЫХ РАБОТ № {number} от {dateText}",
        [
            $"по договору № {contract}",
            "Исполнитель: ООО «Ромашка»",
            "Заказчик: ООО «Вектор»",
            "Работы выполнены полностью и в срок. Стороны претензий не имеют.",
        ]);

    private static SampleDocument Contract(string fileName, DateTime modified, string title, string dateText) =>
